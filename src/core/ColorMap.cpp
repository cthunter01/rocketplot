Rgba tableAt(ColorTable table, double t)
{
    t                                                 = clamped(t);
    const std::array<std::uint32_t, kTableSize>* data = tableOf(table);
    if (data == nullptr)
    {
        return computed(table, t);
    }
    const double      position = t * static_cast<double>(kTableSize - 1);
    const auto        below    = static_cast<std::size_t>(std::floor(position));
    const std::size_t above    = std::min(below + 1, kTableSize - 1);
    return mixed(unpacked(data->at(below)), unpacked(data->at(above)),
                 position - static_cast<double>(below));
}

Rgba gradientAt(std::span<const GradientStop> stops, double t)
{
    if (stops.empty())
    {
        return {};
    }
    t = clamped(t);
    if (t <= stops.front().position)
    {
        return stops.front().color;
    }
    for (std::size_t i = 1; i < stops.size(); ++i)
    {
        const GradientStop& from = stops[i - 1];
        const GradientStop& to   = stops[i];
        if (t <= to.position)
        {
            const double span = to.position - from.position;
            return span > 0.0 ? mixed(from.color, to.color, (t - from.position) / span) : to.color;
        }
    }
    return stops.back().color;
}

Lut buildLut(ColorTable table)
{
    Lut lut;
    for (std::size_t i = 0; i < kLutSize; ++i)
    {
        lut.at(i) = tableAt(table, static_cast<double>(i) / static_cast<double>(kLutSize - 1));
    }
    return lut;
}

Lut buildLut(std::span<const GradientStop> stops)
{
    Lut lut;
    for (std::size_t i = 0; i < kLutSize; ++i)
    {
        lut.at(i) = gradientAt(stops, static_cast<double>(i) / static_cast<double>(kLutSize - 1));
    }
    return lut;
}

Rgba lutAt(const Lut& lut, double t)
{
    return lut.at(
        static_cast<std::size_t>(std::lround(clamped(t) * static_cast<double>(kLutSize - 1))));
}

