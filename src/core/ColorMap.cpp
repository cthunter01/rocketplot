constexpr Rgba unpacked(std::uint32_t rgb)
{
    return {.r = static_cast<std::uint8_t>((rgb >> 16U) & 0xffU),
            .g = static_cast<std::uint8_t>((rgb >> 8U) & 0xffU),
            .b = static_cast<std::uint8_t>(rgb & 0xffU)};
}

// The color between @p from and @p to at @p share of the way.
Rgba mixed(Rgba from, Rgba to, double share)
{
    const auto channel = [share](std::uint8_t a, std::uint8_t b) {
        return static_cast<std::uint8_t>(
            std::lround(static_cast<double>(a) + (share * (static_cast<double>(b) - a))));
    };
    return {.r = channel(from.r, to.r),
            .g = channel(from.g, to.g),
            .b = channel(from.b, to.b),
            .a = channel(from.a, to.a)};
}

double clamped(double t)
{
    return std::isnan(t) ? 0.0 : std::clamp(t, 0.0, 1.0);
}

// The entries of the tables that aren't tables: gray, and blue through white to red.
Rgba computed(ColorTable table, double t)
{
    constexpr Rgba kBlack{.r = 0, .g = 0, .b = 0};
    constexpr Rgba kWhite{.r = 255, .g = 255, .b = 255};
    constexpr Rgba kBlue{.r = 0, .g = 0, .b = 255};
    constexpr Rgba kRed{.r = 255, .g = 0, .b = 0};
    if (table == ColorTable::GRAY)
    {
        return mixed(kBlack, kWhite, t);
    }
    return t < 0.5 ? mixed(kBlue, kWhite, 2.0 * t) : mixed(kWhite, kRed, (2.0 * t) - 1.0);
}

const std::array<std::uint32_t, kTableSize>* tableOf(ColorTable table)
{
    switch (table)
    {
        case ColorTable::VIRIDIS:
            return &kViridis;
        case ColorTable::PLASMA:
            return &kPlasma;
        case ColorTable::INFERNO:
            return &kInferno;
        case ColorTable::MAGMA:
            return &kMagma;
        case ColorTable::CIVIDIS:
            return &kCividis;
        case ColorTable::COOL_WARM:
            return &kCoolWarm;
        case ColorTable::GRAY:
        case ColorTable::BLUE_RED:
            break;
    }
    return nullptr;
}

